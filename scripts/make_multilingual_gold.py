def main() -> int:
    english = [json.loads(line) for line in GOLD.read_text(encoding="utf-8").splitlines() if line]
    rows = []
    for language in ("hi", "kn"):
        for g in english:
            rows.append(
                {
                    **g,
                    "id": f"{g['id']}-{language}",
                    "language": language,
                    "query": TRANSLATIONS[g["id"]][language],
                    "source_id": g["id"],
                    "status": "draft-translated",
                }
            )
    OUT.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )
    print(f"wrote {len(rows)} queries to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
